"""PROJ change watch: which PROJ projections exist, which proj4rs has, which
the projections suite covers, and which PROJ projection sources changed
recently.

Reads a PROJ checkout (PROJ_HEAD entries in src/projections/*.cpp and git
history of that directory) and a proj4rs checkout (declare_proj! entries in
proj4rs/src/projections/mod.rs). Writes results/tracker/watch.json and
results/tracker/README.md.

Usage (from the repository root):
  python3 tracker/watch.py --proj PROJ_DIR --proj4rs PROJ4RS_DIR [--since "180 days ago"]
tracker/checkout.sh makes both checkouts with enough history.
"""

import argparse
import datetime
import json
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUITE = ROOT / "suites" / "projections" / "projections.json"
OUT = ROOT / "results" / "tracker"
PROJ_URL = "https://github.com/OSGeo/PROJ"

GENERATED = "<!-- generated by tracker/watch.py; do not edit -->\n\n"

HEAD_RE = re.compile(r"PROJ_HEAD\(\s*([a-z0-9_]+)\s*,\s*\"([^\"]*)\"")


def git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True).stdout


def proj_projections(proj):
    out = {}
    for f in sorted((proj / "src" / "projections").glob("*.cpp")):
        for name, desc in HEAD_RE.findall(f.read_text(errors="replace")):
            out[name] = {"file": f.name, "desc": desc}
    return out


def proj4rs_projections(rs):
    text = (rs / "proj4rs" / "src" / "projections" / "mod.rs").read_text()
    return {a.split(",")[-1].strip() for a in re.findall(r"declare_proj!\(([^)]*)\)", text)}


def suite_entries():
    with open(SUITE) as f:
        entries = json.load(f)
    out = {}
    for e in entries:
        name = e["proj"].split()[0].split("=", 1)[1]
        out.setdefault(name, []).append(e["id"])
    return out


def changes(proj, since):
    log = git(proj, "log", "--no-merges", f"--since={since}", "--format=@%H\t%ad\t%s", "--date=short", "--name-only", "--", "src/projections")
    # a shallow clone's boundary commits look as if they added every file
    shallow = proj / ".git" / "shallow"
    boundary = set(shallow.read_text().split()) if shallow.exists() else set()
    out, cur = {}, None
    for line in log.splitlines():
        if line.startswith("@"):
            sha, date, subject = line[1:].split("\t", 2)
            cur = None if sha in boundary else {"sha": sha, "date": date, "subject": subject}
        elif line.strip() and cur:
            out.setdefault(Path(line).name, []).append(cur)
    return out


def ascii(s):
    return "".join(c if ord(c) < 128 else "?" for c in s).replace("|", "&#124;")


def commit_link(c):
    return f"[{c['sha'][:8]}]({PROJ_URL}/commit/{c['sha']}) {c['date']} {ascii(c['subject'])}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--proj", required=True, type=Path)
    ap.add_argument("--proj4rs", required=True, type=Path)
    ap.add_argument("--since", default="180 days ago")
    a = ap.parse_args()

    proj = proj_projections(a.proj)
    ported = proj4rs_projections(a.proj4rs)
    suite = suite_entries()
    changed = changes(a.proj, a.since)
    rows = []
    for name, info in sorted(proj.items()):
        rows.append({"name": name, "desc": info["desc"], "file": info["file"], "proj4rs": name in ported,
                     "suite": suite.get(name, []), "proj_commits": changed.get(info["file"], [])})
    head = git(a.proj, "log", "-1", "--format=%H\t%ad", "--date=short").strip().split("\t")
    rs_head = git(a.proj4rs, "log", "-1", "--format=%H\t%ad", "--date=short").strip().split("\t")
    env = {"generated": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
           "proj_head": head[0], "proj_date": head[1], "proj4rs_head": rs_head[0], "proj4rs_date": rs_head[1],
           "since": a.since}
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "watch.json", "w") as f:
        json.dump({"environment": env, "projections": rows}, f, indent=1, ensure_ascii=True)
        f.write("\n")

    n_port = sum(r["proj4rs"] for r in rows)
    look = [r for r in rows if r["proj_commits"] and (r["proj4rs"] or r["suite"])]
    active = [r for r in rows if r["proj_commits"] and not (r["proj4rs"] or r["suite"])]
    unported = [r for r in rows if not r["proj4rs"]]
    out = ["# PROJ change watch\n\n", GENERATED,
           f"PROJ [{head[0][:8]}]({PROJ_URL}/commit/{head[0]}) ({head[1]}) has {len(rows)} projections in "
           f"`src/projections/`; proj4rs [{rs_head[0][:8]}](https://github.com/3liz/proj4rs/commit/{rs_head[0]}) "
           f"({rs_head[1]}) has {n_port} of them; the [projections suite](../projections/README.md) covers "
           f"{sum(bool(r['suite']) for r in rows)}. Commits are those touching `src/projections/` since {a.since}.\n\n",
           "## Changed in PROJ, ported or in the suite: worth a look\n\n"
           "A PROJ change here may need to follow into proj4rs, and the suite shows whether the ports still agree.\n\n"
           "| projection | proj4rs | suite | PROJ commits |\n|---|---|---|---|\n"]
    for r in look:
        suite_links = ", ".join(f"[{i}](../projections/pages/{i}.md)" for i in r["suite"])
        out.append(f"| {r['name']} | {'yes' if r['proj4rs'] else ''} | {suite_links} | "
                   + "<br>".join(commit_link(c) for c in r["proj_commits"]) + " |\n")
    out.append("\n## Changed in PROJ, not ported and not in the suite\n\n| projection | description | PROJ commits |\n|---|---|---|\n")
    for r in active:
        out.append(f"| {r['name']} | {ascii(r['desc'])} | " + "<br>".join(commit_link(c) for c in r["proj_commits"]) + " |\n")
    out.append(f"\n## Not in proj4rs ({len(unported)})\n\n"
               + ", ".join(f"{r['name']}" + (" (in suite)" if r["suite"] else "") for r in unported) + "\n")
    with open(OUT / "README.md", "w") as f:
        f.write("".join(out))
    print(f"PROJ {head[0][:8]}: {len(rows)} projections, {n_port} in proj4rs, {len(look)} changed and tracked, "
          f"{len(active)} changed and untracked; wrote {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
