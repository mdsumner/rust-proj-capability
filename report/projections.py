"""Judge the projections suite and write its pages.

Reads suites/projections/reference.json (PROJ, from oracle/projections.py)
and one or more engine result files (JSON lines from engines/rust-projections
and engines/js), judges every (projection, engine) with the same code, and
writes:

  results/projections/summary.json   one record per (projection, engine): metrics and verdict
  results/projections/README.md      verdict grid, projections by engines, and verdict counts
  results/projections/proj-check.md  PROJ's own round trip, per projection
  results/projections/pages/<id>.md  one page per projection: metrics per engine and its map
  results/projections/maps/<id>.svg  graticule drawn by each engine, PROJ's points as rings

Usage (from the repository root):
  python3 report/projections.py results/projections/engines-rust.jsonl results/projections/engines-js.jsonl
Output is ASCII; links are relative so the tree renders on GitHub and GitHub Pages.
"""

import json
import math
import os
import shutil
import sys
from collections import Counter, OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REFERENCE = os.path.join(ROOT, "suites", "projections", "reference.json")
OUT = os.path.join(ROOT, "results", "projections")

GENERATED = "<!-- generated by report/projections.py from suites/projections/reference.json and engine results; do not edit -->\n\n"

# Display order; engines not listed here follow in the order they appear.
ENGINE_ORDER = ["proj4rs", "proj4rs-main", "proj4rs-wasm", "proj-core", "wbprojection", "terrio", "geodesy", "proj4js", "math.gl"]

# Tolerances: forward in projected units (metres for every entry in the
# suite), inverse in degrees of arc (longitude scaled by cos(lat)).
EXACT_M, CLOSE_M = 1e-3, 1.0
EXACT_DEG, CLOSE_DEG = 1e-8, 1e-5

VERDICTS = OrderedDict([
    ("exact", f"forward within {EXACT_M * 1000:g} mm and inverse within {EXACT_DEG:g} deg of PROJ at every point PROJ answers"),
    ("close", f"forward within {CLOSE_M:g} m and inverse within {CLOSE_DEG:g} deg"),
    ("off", "larger differences somewhere (worst shown)"),
    ("gaps", "agrees where it answers, but gives no result at some points where PROJ does"),
    ("unsupported", "the engine refused the projection string"),
    ("no-reference", "PROJ refused this projection, so there is nothing to judge against"),
])
SHORT = {"exact": "exact", "close": "close", "off": "OFF", "gaps": "gaps", "unsupported": "--", "no-reference": "no ref"}


def ascii(s):
    return "".join(c if ord(c) < 128 else "?" for c in str(s))


def cell(s):
    return ascii(s).replace("|", "&#124;").replace("\n", " ").strip()


def arc_deg(a, b):
    """Angular difference in degrees between two lon/lat points, longitude scaled by cos(lat)."""
    dlon = (a[0] - b[0] + 180.0) % 360.0 - 180.0
    return math.hypot(dlon * math.cos(math.radians(b[1])), a[1] - b[1])


def metres(d):
    if d is None:
        return ""
    if d == 0:
        return "0"
    if d < 1e-6:
        return "<1 nm"
    if d < 1:
        return f"{d * 1000:.3g} mm"
    if d < 1000:
        return f"{d:.4g} m"
    return f"{d / 1000:,.4g} km"


def degrees(d):
    if d is None:
        return ""
    return "0" if d == 0 else f"{d:.2g} deg"


def judge(ref, res):
    """Metrics and verdict for one engine on one projection."""
    m = {"projection": ref["id"], "engine": res["engine"], "engine_version": res.get("engine_version"),
         "supported": bool(res.get("supported"))}
    if not m["supported"]:
        m.update(verdict="unsupported", error=res.get("error"))
        return m
    if "error" in ref:
        m["verdict"] = "no-reference"
        return m
    pf, pi, pts = ref.get("fwd", []), ref.get("inv", []), ref["points"]
    ef, ei = res.get("fwd", []), res.get("inv", [])
    fwd_max = inv_max = 0.0
    fwd_at = inv_at = None
    fwd_missing = fwd_extra = inv_missing = 0
    for i, p in enumerate(pf):
        e = ef[i] if i < len(ef) else None
        if p is None:
            fwd_extra += e is not None
            continue
        if e is None:
            fwd_missing += 1
            continue
        d = math.hypot(e[0] - p[0], e[1] - p[1])
        if d > fwd_max:
            fwd_max, fwd_at = d, pts[i]
    for i, p in enumerate(pi):
        if p is None:
            continue
        e = ei[i] if i < len(ei) else None
        if e is None:
            inv_missing += 1
            continue
        d = arc_deg(e, p)
        if d > inv_max:
            inv_max, inv_at = d, pts[i]
    m.update(points=len(pts), fwd_max_m=fwd_max, fwd_worst_at=fwd_at, fwd_missing=fwd_missing,
             fwd_extra=fwd_extra, inv_max_deg=inv_max, inv_worst_at=inv_at, inv_missing=inv_missing)
    if fwd_max < EXACT_M and inv_max < EXACT_DEG:
        v = "exact"
    elif fwd_max < CLOSE_M and inv_max < CLOSE_DEG:
        v = "close"
    else:
        v = "off"
    if v != "off" and (fwd_missing or inv_missing):
        v = "gaps"
    m["verdict"] = v
    return m


def known_note(ref, engine):
    """A documented difference in projections.json, keyed by engine name or its prefix (proj4rs covers proj4rs-main)."""
    for k, note in (ref.get("known") or {}).items():
        if engine == k or engine.startswith(k + "-"):
            return note
    return None


def short(m):
    s = SHORT[m["verdict"]]
    if m["verdict"] == "off":
        worst = metres(m["fwd_max_m"]) if m["fwd_max_m"] >= CLOSE_M else degrees(m["inv_max_deg"])
        s += " " + worst
    if m.get("known"):
        s += " (known)"
    return s


def proj_check(ref):
    """PROJ's own round trip: its inverse of its forward against the input point."""
    worst, at, failed = 0.0, None, 0
    for p, f, i in zip(ref["points"], ref.get("fwd", []), ref.get("inv", [])):
        if f is None:
            continue
        if i is None:
            failed += 1
            continue
        d = arc_deg(i, p)
        if d > worst:
            worst, at = d, p
    return {"max_deg": worst, "at": at, "inverse_failed": failed}


# ---------------------------------------------------------------- maps

PANEL_W, PANEL_H, PAD, COLS = 240, 180, 14, 4


def svg_panel(ref, res, m, ox, oy, bounds):
    """One engine's graticule (lines between neighbouring points) with PROJ's points as rings."""
    x0, y0, x1, y1 = bounds
    sx = (PANEL_W - 2 * PAD) / ((x1 - x0) or 1)
    sy = (PANEL_H - 2 * PAD - 16) / ((y1 - y0) or 1)
    s = min(sx, sy)
    cx = ox + PANEL_W / 2 - s * (x0 + x1) / 2
    cy = oy + 16 + (PANEL_H - 16) / 2 + s * (y0 + y1) / 2

    def xy(p):
        return (round(cx + s * p[0], 1), round(cy - s * p[1], 1))

    out = [f'<rect x="{ox}" y="{oy}" width="{PANEL_W}" height="{PANEL_H}" fill="none" stroke="#ccc"/>',
           f'<text x="{ox + 6}" y="{oy + 13}" font-size="11" fill="#333">{ascii(res["engine"])}: {ascii(short(m))}</text>']
    if not m["supported"]:
        out.append(f'<text x="{ox + PANEL_W / 2}" y="{oy + PANEL_H / 2}" font-size="11" text-anchor="middle" fill="#999">not supported</text>')
        return out
    ef, pf = res.get("fwd", []), ref.get("fwd", [])
    w = ref["window"]
    nlon = int(round((w["lon"][1] - w["lon"][0]) / w["step"])) + 1
    span = max(x1 - x0, y1 - y0)
    segs = []
    for i, e in enumerate(ef):
        if e is None:
            continue
        for j in (i + 1, i + nlon):  # east and north neighbours
            if j < len(ef) and ef[j] is not None and (j != i + 1 or (i + 1) % nlon):
                if math.hypot(ef[j][0] - e[0], ef[j][1] - e[1]) < span / 3:  # skip seams
                    a, b = xy(e), xy(ef[j])
                    segs.append(f"M{a[0]} {a[1]}L{b[0]} {b[1]}")
    out.append(f'<path d="{"".join(segs)}" fill="none" stroke="#6a8caf" stroke-width="0.8"/>')
    for i, p in enumerate(pf):
        if p is None:
            continue
        a = xy(p)
        e = ef[i] if i < len(ef) else None
        miss = e is None or math.hypot(e[0] - p[0], e[1] - p[1]) >= CLOSE_M
        out.append(f'<circle cx="{a[0]}" cy="{a[1]}" r="{2.6 if miss else 1.6}" fill="none" '
                   f'stroke="{"#d62728" if miss else "#999"}" stroke-width="{1.2 if miss else 0.6}"/>')
    return out


def svg_map(ref, results, metrics):
    good = [p for p in ref.get("fwd", []) if p is not None]
    if not good:
        return None
    xs, ys = [p[0] for p in good], [p[1] for p in good]
    bounds = (min(xs), min(ys), max(xs), max(ys))
    n = len(results)
    rows = (n + COLS - 1) // COLS
    W, H = COLS * PANEL_W + (COLS + 1) * 8, rows * PANEL_H + (rows + 1) * 8 + 24
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" font-family="sans-serif">',
           f'<rect width="{W}" height="{H}" fill="#fff"/>',
           f'<text x="8" y="17" font-size="13" fill="#111">{ascii(ref["id"])}: {ascii(ref["proj"])}</text>']
    for k, (res, m) in enumerate(zip(results, metrics)):
        ox = 8 + (k % COLS) * (PANEL_W + 8)
        oy = 24 + 8 + (k // COLS) * (PANEL_H + 8)
        out += svg_panel(ref, res, m, ox, oy, bounds)
    out.append("</svg>")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- pages

def page(ref, metrics, check, env, has_map):
    out = [f"# {ref['id']}\n\n", GENERATED,
           "[Projections grid](../README.md) / [PROJ round trip](../proj-check.md) / "
           "[suite](../../../suites/projections/README.md)\n\n",
           f"```\n{ascii(ref['proj'])}\n```\n\n",
           f"Source lon/lat for every engine: `{ascii(ref['geographic'])}`. "
           f"Window lon {ref['window']['lon']}, lat {ref['window']['lat']}, every {ref['window']['step']} deg: "
           f"{len(ref['points'])} points, {sum(p is not None for p in ref.get('fwd', []))} projected by PROJ "
           f"{env['proj_version']}.\n\n"]
    if ref.get("why"):
        out.append(f"Why this entry: {ascii(ref['why'])}.\n\n")
    if "error" in ref:
        out.append(f"PROJ refused this projection: {cell(ref['error'])}\n\n")
    out.append(f"PROJ round trip (its inverse of its forward): worst {degrees(check['max_deg'])}"
               + (f" at {check['at']}" if check["at"] else "")
               + (f", {check['inverse_failed']} inverse failures" if check["inverse_failed"] else "") + ".\n\n")
    if has_map:
        out.append(f"![{ref['id']} by engine](../maps/{ref['id']}.svg)\n\n"
                   "Blue: the graticule as each engine draws it. Grey rings: PROJ's points. "
                   "Red rings: points where the engine is 1 m or more from PROJ, or gives nothing.\n\n")
    out.append("| engine | version | verdict | forward, worst | at lon, lat | inverse, worst | at lon, lat | "
               "no forward | no inverse | answers where PROJ refuses |\n|---|---|---|---|---|---|---|---|---|---|\n")
    for m in metrics:
        if not m["supported"] or m["verdict"] == "no-reference":
            out.append(f"| {m['engine']} | {cell(m['engine_version'])} | {short(m)} | {cell(m.get('error') or '')} | | | | | | |\n")
            continue
        out.append(f"| {m['engine']} | {cell(m['engine_version'])} | {short(m)} | {metres(m['fwd_max_m'])} | "
                   f"{m['fwd_worst_at'] or ''} | {degrees(m['inv_max_deg'])} | {m['inv_worst_at'] or ''} | "
                   f"{m['fwd_missing'] or ''} | {m['inv_missing'] or ''} | {m['fwd_extra'] or ''} |\n")
    notes = [(m["engine"], m["known"]) for m in metrics if m.get("known")]
    if notes:
        out.append("\nKnown differences, recorded in [projections.json](../../../suites/projections/projections.json):\n\n")
        out += [f"- {e}: {cell(n)}\n" for e, n in notes]
    return "".join(out)


def readme(refs, grid, engines, env, counts):
    out = ["# Projections suite: results\n\n", GENERATED,
           f"{len(refs)} projection setups, each a grid of lon/lat points run through PROJ "
           f"{env['proj_version']}" + (f" (git {env['proj_git_sha']})" if env.get("proj_git_sha") else "")
           + f" with `Transformer.from_pipeline` and through every engine. Generated {env['generated']}. "
           "Each projection links to a page with the numbers and a map drawn by every engine; "
           "[proj-check.md](proj-check.md) is PROJ's own round trip. Machine-readable: `summary.json`.\n\n",
           "| projection | " + " | ".join(engines) + " |\n|---|" + "---|" * len(engines) + "\n"]
    for ref in refs:
        row = grid[ref["id"]]
        out.append(f"| [{ref['id']}](pages/{ref['id']}.md) | " + " | ".join(short(row[e]) if e in row else "" for e in engines) + " |\n")
    out.append("\n## Verdict counts\n\n| engine | " + " | ".join(SHORT[v] for v in VERDICTS) + " |\n|---|" + "---|" * len(VERDICTS) + "\n")
    for e in engines:
        out.append(f"| {e} | " + " | ".join(str(counts[e].get(v, 0)) for v in VERDICTS) + " |\n")
    out.append("\n| verdict | meaning |\n|---|---|\n")
    out += [f"| {SHORT[k]} | {k}: {v} |\n" for k, v in VERDICTS.items()]
    out.append("\n(known) marks a difference recorded with a reason in "
               "[projections.json](../../suites/projections/projections.json).\n")
    return "".join(out)


def proj_check_page(refs, checks, env):
    out = ["# PROJ round trip\n\n", GENERATED,
           f"PROJ {env['proj_version']}'s inverse of its own forward result, against the input point, "
           "for every projection in the suite. A large value here is a question for PROJ, not for the ports: "
           "the ports are judged against PROJ's inverse, so this page checks that reference. "
           "Triage of what it raises: [proj-concerns.md](proj-concerns.md).\n\n"
           "| projection | worst | at lon, lat | inverse failures |\n|---|---|---|---|\n"]
    for ref in sorted(refs, key=lambda r: -checks[r["id"]]["max_deg"]):
        c = checks[ref["id"]]
        out.append(f"| [{ref['id']}](pages/{ref['id']}.md) | {degrees(c['max_deg'])} | {c['at'] or ''} | {c['inverse_failed'] or ''} |\n")
    return "".join(out)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    with open(REFERENCE) as f:
        reference = json.load(f)
    env = reference["environment"]
    refs = reference["projections"]
    by_id = {r["id"]: r for r in refs}
    results = OrderedDict()
    for path in sys.argv[1:]:
        with open(path) as f:
            for line in f:
                if line.strip():
                    r = json.loads(line)
                    results[(r["projection"], r["engine"])] = r
    seen = list(OrderedDict.fromkeys(e for _, e in results))
    engines = [e for e in ENGINE_ORDER if e in seen] + [e for e in seen if e not in ENGINE_ORDER]

    for d in ("pages", "maps"):
        shutil.rmtree(os.path.join(OUT, d), ignore_errors=True)
    grid, counts, summary, checks = {}, {e: Counter() for e in engines}, [], {}
    for ref in refs:
        checks[ref["id"]] = proj_check(ref)
        row, ms, rs = {}, [], []
        for e in engines:
            res = results.get((ref["id"], e))
            if res is None:
                continue
            m = judge(ref, res)
            note = known_note(ref, e)
            if note and m["verdict"] != "exact":
                m["known"] = note
            row[e] = m
            counts[e][m["verdict"]] += 1
            ms.append(m)
            rs.append(res)
            summary.append(m)
        grid[ref["id"]] = row
        svg = svg_map(ref, rs, ms)
        if svg:
            write(os.path.join(OUT, "maps", ref["id"] + ".svg"), svg)
        write(os.path.join(OUT, "pages", ref["id"] + ".md"), page(ref, ms, checks[ref["id"]], env, svg is not None))

    write(os.path.join(OUT, "README.md"), readme(refs, grid, engines, env, counts))
    write(os.path.join(OUT, "proj-check.md"), proj_check_page(refs, checks, env))
    with open(os.path.join(OUT, "summary.json"), "w") as f:
        json.dump({"environment": env, "engines": engines, "proj_check": checks, "results": summary},
                  f, indent=1, ensure_ascii=True)
        f.write("\n")
    print(f"judged {len(summary)} (projection, engine) pairs; wrote {os.path.relpath(OUT, ROOT)}/")
    for e in engines:
        print(f"  {e:14s} " + " ".join(f"{v}={counts[e][v]}" for v in VERDICTS if counts[e][v]))


if __name__ == "__main__":
    main()
