"""Write the PROJ concerns page: triaged entries plus untriaged signals.

Reads suites/projections/proj-concerns.json (hand-kept triage) and
results/projections/summary.json (report/projections.py), and writes
results/projections/proj-concerns.md.

Two kinds of signal are raised automatically, per projection:
  roundtrip  PROJ's inverse of its own forward fails at some point, or misses
             the input by more than 1e-8 deg
  consensus  at least two independent engine families are "off" by the same
             amount (worst forward difference within 1% of each other), so
             the difference may be PROJ's rather than theirs (proj4rs builds
             count once, math.gl counts with proj4js, and terrio-crs counts
             with wbprojection where it uses its wbprojection fallback)
A signal an entry lists under "signals" is shown with that entry; any other
signal is listed as untriaged. Entries change status only by hand.

Usage (from the repository root):
  python3 report/proj_concerns.py
"""

import json
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TRIAGE = os.path.join(ROOT, "suites", "projections", "proj-concerns.json")
SUMMARY = os.path.join(ROOT, "results", "projections", "summary.json")
OUT = os.path.join(ROOT, "results", "projections", "proj-concerns.md")
GENERATED = ("<!-- generated by report/proj_concerns.py from suites/projections/proj-concerns.json "
             "and summary.json; do not edit -->\n\n")

# Engines that share code count once: proj4rs in three builds, and math.gl ports proj4js.
FAMILY = {"proj4rs": "proj4rs", "proj4rs-main": "proj4rs", "proj4rs-wasm": "proj4rs",
          "math.gl": "proj4js"}
# terrio-crs runs these through its wbprojection fallback; the rest are its own.
FALLBACK = {"terrio-crs": ("wbprojection", {"eck4", "natearth", "hammer"})}


def family(engine, pid):
    fb = FALLBACK.get(engine)
    if fb and pid in fb[1]:
        return fb[0]
    return FAMILY.get(engine, engine)
ORDER = ["suspected", "confirmed", "drafted", "reported", "fixed", "not-a-bug"]
ROUNDTRIP_DEG = 1e-8


def roundtrip_signals(summary):
    out = {}
    for pid, c in summary["proj_check"].items():
        if c["inverse_failed"] or c["max_deg"] > ROUNDTRIP_DEG:
            parts = []
            if c["inverse_failed"]:
                parts.append(f"{c['inverse_failed']} inverse failures")
            if c["max_deg"] > ROUNDTRIP_DEG:
                parts.append(f"worst {c['max_deg']:.2g} deg at {c['at']}")
            out[pid] = ", ".join(parts)
    return out


def consensus_signals(summary):
    off = defaultdict(dict)
    for r in summary["results"]:
        if r["verdict"] == "off" and r.get("fwd_max_m"):
            fam = family(r["engine"], r["projection"])
            off[r["projection"]].setdefault(fam, (r["engine"], r["fwd_max_m"], r["inv_max_deg"]))
    out = {}
    for pid, fams in off.items():
        groups = []
        for fam, (eng, d, inv) in fams.items():
            for g in groups:
                if abs(g[0] - d) <= 0.01 * max(g[0], d):
                    g[2].append(eng)
                    break
            else:
                groups.append([d, inv or 0.0, [eng]])
        d, inv, engs = max(groups, key=lambda g: len(g[2]))
        if len(engs) >= 2:
            out[pid] = (f"{', '.join(engs)} agree with each other and differ from PROJ by up to "
                        f"{d:,.4g} m forward, {inv:.2g} deg inverse")
    return out


def links(entry):
    if not entry["proj_links"]:
        return "nothing to send" if entry["status"] == "not-a-bug" else "not sent to PROJ"
    return ", ".join(f"[{u.rstrip('/').split('/')[-1][:8]}]({u})" for u in entry["proj_links"])


def page(triage, summary):
    signals = {"roundtrip": roundtrip_signals(summary), "consensus": consensus_signals(summary)}
    claimed = {(pid, kind) for e in triage["concerns"] for pid, kinds in e["signals"].items() for kind in kinds}
    env = summary["environment"]
    out = ["# PROJ concerns\n\n", GENERATED,
           "Concerns about PROJ itself, as opposed to the ports, found by the benchmark. "
           f"Signals are computed against PROJ {env['proj_version']}"
           + (f" (git {env['proj_git_sha'][:8]})" if env.get("proj_git_sha") else "")
           + " on every run; whether a signal is a real problem is decided by a person and recorded in "
           "[proj-concerns.json](../../suites/projections/proj-concerns.json).\n\n"
           "**Nothing here has been sent to PROJ unless the entry links to a PROJ issue, pull request "
           "or commit.**\n\n"]
    out.append("| status | meaning |\n|---|---|\n")
    for s in ORDER:
        out.append(f"| {s} | {triage['statuses'][s]} |\n")
    out.append("\n## Triaged\n\n| status | concern | projections | found | PROJ |\n|---|---|---|---|---|\n")
    entries = sorted(triage["concerns"], key=lambda e: (ORDER.index(e["status"]), e["found"]))
    for e in entries:
        projs = ", ".join(f"[{p}](pages/{p}.md)" if os.path.exists(os.path.join(ROOT, "results", "projections", "pages", p + ".md"))
                          else p for p in e["projections"])
        out.append(f"| {e['status']} | [{e['title']}](#{e['id']}) | {projs} | {e['found']} | {links(e)} |\n")

    out.append("\n## Untriaged signals\n\n")
    loose = [(pid, kind, text) for kind, sig in signals.items() for pid, text in sorted(sig.items())
             if (pid, kind) not in claimed]
    if loose:
        out.append("Raised by this run and not yet accounted for by an entry above.\n\n"
                   "| projection | signal | what |\n|---|---|---|\n")
        for pid, kind, text in loose:
            out.append(f"| [{pid}](pages/{pid}.md) | {kind} | {text} |\n")
    else:
        out.append("None: every signal in this run is accounted for above.\n")

    out.append("\n## Details\n")
    for e in entries:
        out.append(f"\n### {e['title']}\n\n<a id=\"{e['id']}\"></a>"
                   f"Status: **{e['status']}**. Found {e['found']}. PROJ: {links(e)}.\n\n{e['detail']}\n")
        live = [f"{kind} on {pid}: {signals[kind][pid]}" for pid, kinds in e["signals"].items()
                for kind in kinds if pid in signals[kind]]
        gone = [f"{kind} on {pid}" for pid, kinds in e["signals"].items()
                for kind in kinds if pid not in signals[kind]]
        if live:
            out.append("\nThis run: " + "; ".join(live) + ".\n")
        if gone:
            out.append("\nNo longer raised in this run: " + "; ".join(gone) + ".\n")
    return "".join(out)


def main():
    with open(TRIAGE) as f:
        triage = json.load(f)
    with open(SUMMARY) as f:
        summary = json.load(f)
    for e in triage["concerns"]:
        if e["status"] not in ORDER:
            raise SystemExit(f"{e['id']}: unknown status {e['status']!r}")
    text = page(triage, summary)
    text.encode("ascii")
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
