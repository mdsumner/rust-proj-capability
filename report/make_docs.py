"""Generate the derived markdown pages from fixtures/crs.json and
results/results.jsonl. Hand-written pages are never touched.

Writes:
  fixtures/FIXTURES.md         catalog: one row per fixture
  fixtures/catalog/<id>.md     one page per fixture: inputs, oracle, every candidate's result
  results/per-fixture.md       verdict grid, fixture ids linked to their pages
  results/README.md            what the result files are, verdict counts

Usage (from the repository root): python3 report/make_docs.py
Output is ASCII; links are relative so the tree renders on GitHub and GitHub Pages.
"""

import json
import os
import shutil
from collections import Counter, OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRS = os.path.join(ROOT, "fixtures", "crs.json")
RESULTS = os.path.join(ROOT, "results", "results.jsonl")
CATALOG = os.path.join(ROOT, "fixtures", "catalog")

GENERATED = "<!-- generated by report/make_docs.py from fixtures/crs.json and results/results.jsonl; do not edit -->\n\n"

GROUPS = OrderedDict([
    ("seed", "Seed list (the sidebyside crs/ seeds)"),
    ("pair", "CRS-to-CRS pairs"),
    ("form", "Input forms, units, unknown and invalid input"),
    ("method", "Projection methods"),
    ("edge", "Edge cases: pole, seam, antipode, far from the meridian"),
])

VERDICTS = OrderedDict([
    ("exact", "within 1 mm of PROJ"),
    ("close", "within 1 m of PROJ"),
    ("off", "1 m or more from PROJ (distance shown)"),
    ("axis-swapped", "matches PROJ with the axes swapped"),
    ("failed", "both CRSs resolved but no finite result"),
    ("unresolved", "could not build one of the CRSs from the input"),
    ("n/a", "the input does not apply to this candidate (crs-definitions takes authority codes only)"),
    ("refused-like-oracle", "PROJ refused this fixture and so did the candidate"),
    ("answered-where-oracle-refused", "PROJ refused but the candidate returned a value"),
])

SHORT = {"exact": "exact", "close": "close", "off": "OFF", "failed": "fail", "unresolved": "--",
         "n/a": "n/a", "refused-like-oracle": "refuse", "answered-where-oracle-refused": "ANSWER",
         "axis-swapped": "SWAP"}


def ascii(s):
    return "".join(c if ord(c) < 128 else f"&#{ord(c)};" for c in str(s))


def cell(s):
    """Text safe for a markdown table cell."""
    if s is None:
        return ""
    return ascii(str(s)).replace("|", "&#124;").replace("\n", " ").strip()


def metres(d):
    if d is None:
        return ""
    if d == 0:
        return "0 mm"
    if d < 1e-6:
        return "<0.001 mm"
    if d < 1:
        return f"{d * 1000:.3g} mm"
    if d < 1000:
        return f"{d:.4g} m"
    return f"{d / 1000:,.4g} km"


def coords(v, nd=6):
    if not v:
        return ""
    out = []
    for x in v:
        if isinstance(x, (int, float)):
            out.append(f"{x:.{nd}f}".rstrip("0").rstrip(".") if abs(x) < 1e6 else f"{x:.3f}")
        else:
            out.append(str(x))
    return ", ".join(out)


def short_def(defn, ref):
    """One-line label for a CRS definition."""
    if ref and ref.startswith("@export:"):
        _, auth, code, fmt = ref.split(":")
        return f"{auth}:{code} as {fmt.replace('-BOUND', ' (bound)')}"
    if defn is None:
        return ref or ""
    return defn if len(defn) <= 70 else defn[:67] + "..."


def short_verdict(r):
    s = SHORT.get(r["verdict"], r["verdict"])
    if r["verdict"] in ("close", "off") and r.get("diff_m") is not None:
        s += " " + metres(r["diff_m"])
    return s


def fixture_link(fid, prefix):
    return f"[{fid}]({prefix}{fid}.md)"


def code_block(text, lang=""):
    return f"```{lang}\n{ascii(text)}\n```\n"


def definition_block(label, defn):
    if defn is None:
        return f"- {label}: (none)\n"
    if len(defn) <= 100 and "\n" not in defn:
        return f"- {label}: `{ascii(defn)}`\n"
    lang = "json" if defn.lstrip().startswith("{") else ""
    return (f"- {label}:\n\n<details><summary>{len(defn)} characters, click to expand</summary>\n\n"
            + code_block(defn, lang) + "\n</details>\n\n")


def load():
    with open(CRS) as f:
        crs = json.load(f)
    rows = [json.loads(l) for l in open(RESULTS)]
    rows = [r for r in rows if not r.get("skipped")]
    return crs, rows


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def environment_lines(env):
    return [
        f"- PROJ {env['proj_version']} ({ascii(env['projinfo_banner'])}), pyproj {env['pyproj_version']}",
        f"- proj.db: EPSG {env['epsg_version']} ({env['epsg_date']}), ESRI {ascii(env['esri_version'])}",
        f"- grids: {ascii(env['grid_configuration'])}; grid files present: {len(env['grid_files_present'])}",
        f"- network enabled: {env['network_enabled']}",
        f"- axis order: {ascii(env['axis_order'])}",
        f"- oracle generated {env['generated']}, schema_version {env.get('schema_version')}",
    ]


def catalog_index(crs, by_fixture):
    env = crs["environment"]
    out = ["# Fixture catalog\n", GENERATED,
           f"{len(crs['fixtures'])} fixtures. Each id links to a page with the full input definitions, "
           "what PROJ did, and every candidate's result. Field meanings: [README.md](README.md#schema). "
           "Verdict grid across candidates: [../results/per-fixture.md](../results/per-fixture.md).\n",
           "Oracle configuration:\n", *[l + "\n" for l in environment_lines(env)], "\n"]
    for g, title in GROUPS.items():
        fx = [f for f in crs["fixtures"] if f["group"] == g]
        if not fx:
            continue
        out.append(f"## {title}\n\n")
        out.append("| fixture | source | destination | point | PROJ operation | accuracy | best op available | layers | note |\n")
        out.append("|---|---|---|---|---|---|---|---|---|\n")
        for f in fx:
            o = f["oracle"]
            op = o.get("op") or {}
            if not o.get("executed"):
                opname = "refused: " + (o.get("error") or "")[:80]
            else:
                opname = op.get("name", "")
            acc = op.get("accuracy")
            acc = "" if acc is None or acc < 0 else f"{acc:g} m"
            best = {True: "yes", False: "NO (grid missing)", None: ""}[o.get("best_available")]
            out.append("| " + " | ".join([
                fixture_link(f["id"], "catalog/"),
                cell(short_def(f["src"], f["src_ref"])),
                cell(short_def(f.get("dst"), f["dst_ref"])),
                cell(coords(f.get("point"))),
                cell(opname),
                cell(acc),
                cell(best),
                cell(", ".join(f.get("layers", []))),
                cell(f.get("note", "")),
            ]) + " |\n")
        out.append("\n")
    return "".join(out)


def fixture_page(f, results, by_id):
    o = f["oracle"]
    op = o.get("op") or {}
    out = [f"# {f['id']}\n\n", GENERATED,
           f"[Fixture catalog](../FIXTURES.md) / [verdict grid](../../results/per-fixture.md) / "
           f"[capability matrix](../../capability-matrix.md)\n\n"]
    if f.get("note"):
        out.append(f"> {ascii(f['note'])}\n\n")
    out.append(f"- group: {f['group']}; input form: {f['form']}; layers: {', '.join(f.get('layers', []))}\n")
    if f.get("compare_to"):
        out.append(f"- reference fixture: {fixture_link(f['compare_to'], '')} "
                   "(results below also give each candidate's distance from that fixture's PROJ result)\n")
    out.append("\n## Input\n\n")
    out.append(definition_block("source" + (f" (`{f['src_ref']}`)" if f["src_ref"] != f["src"] else ""), f["src"]))
    out.append(definition_block("destination" + (f" (`{ascii(f['dst_ref'])}`)" if f["dst_ref"] != f.get("dst") else ""), f.get("dst")))
    out.append(f"- point (source units, east/north order): `{coords(f.get('point'), 9)}`\n")

    out.append("\n## What PROJ did\n\n")
    if not o.get("resolved", True) or not o.get("executed"):
        out.append(f"PROJ refused: `{ascii(o.get('error', ''))}`\n\n")
    if o.get("src_name"):
        out.append(f"- source: {ascii(o['src_name'])} ({o.get('src_kind')}, {ascii(o.get('src_unit'))})\n")
        out.append(f"- destination: {ascii(o['dst_name'])} ({o.get('dst_kind')}, {ascii(o.get('dst_unit'))})\n")
    if o.get("executed"):
        out.append(f"- forward: `{coords(o.get('fwd'), 9)}`\n")
        if o.get("inv"):
            out.append(f"- inverse of the forward result: `{coords(o.get('inv'), 9)}`\n")
        acc = op.get("accuracy")
        out.append(f"- operation used: {ascii(op.get('name', ''))}"
                   + (f" (accuracy {acc:g} m)" if acc is not None and acc >= 0 else " (accuracy unknown)")
                   + (" [ballpark]" if op.get("ballpark") else "")
                   + (" [single operation]" if op.get("single_operation") else "") + "\n")
        if o.get("best_available") is False:
            out.append("- **the best operation was not available (needs a grid that is not installed); PROJ fell back**\n")
        if op.get("proj"):
            out.append("\nPipeline:\n\n" + code_block(op["proj"]))
    if o.get("candidates"):
        out.append("\nCandidate operations PROJ considered (first six of each kind):\n\n| operation | accuracy | available |\n|---|---|---|\n")
        for c in o["candidates"]:
            acc = "" if c["accuracy"] is None or c["accuracy"] < 0 else f"{c['accuracy']:g} m"
            out.append(f"| {cell(c['name'])} | {acc} | {'yes' if c['available'] else 'no (grid missing)'} |\n")
    for side in ("src", "dst"):
        e = o.get(f"{side}_export")
        if not e:
            continue
        label = "source" if side == "src" else "destination"
        out.append(f"\nPROJ strings a port would be fed for the {label}:\n\n")
        out.append(f"- bare (`proj_as_proj_string`): `{ascii(e.get('proj'))}`\n")
        bound = e.get("proj_bound")
        same = " (identical to bare: PROJ did not bind)" if bound == e.get("proj") else ""
        out.append(f"- bound to WGS84 (`proj_crs_create_bound_crs_to_WGS84`){same}: `{ascii(bound)}`\n")

    out.append("\n## Candidate results\n\n")
    out.append("Candidates are described in [harness/README.md](../../harness/README.md#candidates). "
               "Distances are metres on the ground; 'inverse' is the candidate's inverse of PROJ's forward result.\n\n")
    ref = f.get("compare_to")
    head = ["candidate", "verdict", "distance from PROJ", "inverse distance", "result"]
    if ref:
        head.insert(4, f"distance from {ref}")
    head += ["error or note", "operation reported"]
    out.append("| " + " | ".join(head) + " |\n|" + "---|" * len(head) + "\n")
    for r in results:
        err = r.get("resolve_error") or r.get("exec_error") or r.get("inv_error") or ""
        notes = "; ".join(r.get("notes") or [])
        row = [r["candidate"], SHORT.get(r["verdict"], r["verdict"]), metres(r.get("diff_m")),
               metres(r.get("inv_diff_m")), coords(r.get("fwd"), 6) if r.get("fwd") else ""]
        if ref:
            row.insert(4, metres(r.get("diff_vs_reference_m")))
        row += [(err + ("; " if err and notes else "") + notes)[:240], (r.get("operation") or "")[:160]]
        out.append("| " + " | ".join(cell(x) for x in row) + " |\n")
    fed = [(r["candidate"], r.get("fed_dst")) for r in results if r.get("fed_dst") and r.get("fed_dst") != f.get("dst")]
    if fed:
        out.append("\nDestination definitions actually handed to candidates, where they differ from the input:\n\n")
        for c, d in fed:
            out.append(f"- {c}: `{ascii(d if len(d) < 300 else d[:297] + '...')}`\n")
    return "".join(out)


def verdict_grid(crs, rows, cands):
    grid = {(r["fixture"], r["candidate"]): r for r in rows}
    out = ["# Verdict grid: fixtures by candidates\n\n", GENERATED,
           "Each cell compares the candidate with PROJ on that fixture. Fixture ids link to their pages "
           "([catalog](../fixtures/FIXTURES.md)); candidates are described in "
           "[harness/README.md](../harness/README.md#candidates); layer-by-layer reading in "
           "[capability-matrix.md](../capability-matrix.md).\n\n",
           "| verdict | meaning |\n|---|---|\n",
           *[f"| {SHORT[k]} | {k}: {v} |\n" for k, v in VERDICTS.items()], "\n"]
    for g, title in GROUPS.items():
        fx = [f["id"] for f in crs["fixtures"] if f["group"] == g]
        out.append(f"## {title}\n\n| fixture | " + " | ".join(cands) + " |\n|---|" + "---|" * len(cands) + "\n")
        for fid in fx:
            out.append(f"| {fixture_link(fid, '../fixtures/catalog/')} | "
                       + " | ".join(cell(short_verdict(grid[(fid, c)])) if (fid, c) in grid else "" for c in cands) + " |\n")
        out.append("\n")
    return "".join(out)


def results_readme(crs, rows, cands):
    order = list(VERDICTS)
    counts = {c: Counter(r["verdict"] for r in rows if r["candidate"] == c) for c in cands}
    out = ["# Results\n\n", GENERATED,
           f"{len(rows)} judged results: {len(crs['fixtures'])} fixtures by {len(cands)} candidate columns, "
           f"oracle generated {crs['environment']['generated']}.\n\n",
           "| file | contents |\n|---|---|\n",
           "| [per-fixture.md](per-fixture.md) | verdict grid, fixtures by candidates |\n",
           "| `results.jsonl` | one JSON object per (fixture, candidate); fields in [harness/README.md](../harness/README.md#output-fields) |\n",
           "| `combined-build.jsonl` | method-aeqd from the all-features build: evidence of the proj4rs/libproj `geod_*` symbol clash |\n",
           "| `summary.txt` | plain-text grid and counts (report/summarise.py) |\n",
           "| `stderr.txt` | libproj's own stderr during the run (expected errors for the refused fixtures) |\n\n",
           "## Verdict counts\n\n| candidate | " + " | ".join(SHORT[v] for v in order) + " |\n|---|" + "---|" * len(order) + "\n"]
    for c in cands:
        out.append(f"| {c} | " + " | ".join(str(counts[c].get(v, 0)) for v in order) + " |\n")
    out.append("\n| verdict | meaning |\n|---|---|\n")
    out += [f"| {SHORT[k]} | {k}: {v} |\n" for k, v in VERDICTS.items()]
    return "".join(out)


def main():
    crs, rows = load()
    cands = list(OrderedDict.fromkeys(r["candidate"] for r in rows))
    by_fixture = OrderedDict()
    for r in rows:
        by_fixture.setdefault(r["fixture"], []).append(r)
    by_id = {f["id"]: f for f in crs["fixtures"]}

    write(os.path.join(ROOT, "fixtures", "FIXTURES.md"), catalog_index(crs, by_fixture))
    if os.path.isdir(CATALOG):
        shutil.rmtree(CATALOG)
    for f in crs["fixtures"]:
        write(os.path.join(CATALOG, f["id"] + ".md"), fixture_page(f, by_fixture.get(f["id"], []), by_id))
    write(os.path.join(ROOT, "results", "per-fixture.md"), verdict_grid(crs, rows, cands))
    write(os.path.join(ROOT, "results", "README.md"), results_readme(crs, rows, cands))
    print(f"wrote fixtures/FIXTURES.md, {len(crs['fixtures'])} catalog pages, results/per-fixture.md, results/README.md")


if __name__ == "__main__":
    main()
